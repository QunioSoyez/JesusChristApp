// Copies Leaflet's JS and CSS into src/data/leaflet.ts as strings, so the church map
// works without loading the library from a CDN at runtime (map tiles still need network).
//
//   node scripts/build-map-assets.mjs
//
// Leaflet is BSD-2-Clause licensed (see node_modules/leaflet/LICENSE).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'node_modules', 'leaflet', 'dist');

const js = fs.readFileSync(path.join(dist, 'leaflet.js'), 'utf8');
const css = fs.readFileSync(path.join(dist, 'leaflet.css'), 'utf8');
const { version } = JSON.parse(fs.readFileSync(path.join(root, 'node_modules', 'leaflet', 'package.json'), 'utf8'));

if (js.includes('</script')) throw new Error('leaflet.js contains </script and cannot be inlined as-is');

fs.writeFileSync(
  path.join(root, 'src', 'data', 'leaflet.ts'),
  `// Generated by scripts/build-map-assets.mjs from leaflet@${version} (BSD-2-Clause). Do not edit by hand.
export const LEAFLET_VERSION = ${JSON.stringify(version)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
export const LEAFLET_JS = ${JSON.stringify(js)};
`,
);
console.log(`Wrote src/data/leaflet.ts (leaflet ${version}, ${Math.round((js.length + css.length) / 1024)} KB)`);
